import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { drizzle } from 'drizzle-orm/pglite';
import { and, eq } from 'drizzle-orm';
import * as schema from '../db/schema.js';
import { retentionService } from '../src/server/retention.js';
import { cleanTradition, cleanVibe, nextExchangeValues } from '../src/retention/model.js';
import { deliveryDecision } from '../src/server/notifyPolicy.js';

const engine = new PGlite();
try {
  for (const dir of (await readdir('netlify/database/migrations')).sort()) {
    await engine.exec(await readFile(`netlify/database/migrations/${dir}/migration.sql`, 'utf8'));
  }
  const db = drizzle({ client: engine, schema });
  const service = retentionService(db);
  const alice = { id: 'alice', name: 'Alice', email: 'alice@example.test' };
  const bob = { id: 'bob', name: 'Bob', email: 'bob@example.test' };
  const outsider = { id: 'stranger', name: 'Stranger', email: 'stranger@example.test' };
  const vibe = { interests: 'Coffee', avoid: 'Scented products', approach: 'surprise', secondhand: true, handmade: true, experiences: false };
  await service.vibe(alice, { ...vibe, userId: 'bob' });
  assert.deepEqual((await service.vibe(alice)).vibe, vibe);
  assert.equal((await service.vibe(bob)).vibe.interests, '');
  assert.throws(() => cleanVibe({ ...vibe, approach: 'commission-first' }));
  const [list] = await db.insert(schema.wishLists).values({ ownerUserId: 'alice', title: 'Books and coffee' }).returning();
  const [otherList] = await db.insert(schema.wishLists).values({ ownerUserId: 'bob', title: 'Private wishes' }).returning();
  await db.insert(schema.wishItems).values({ listId: list.id, title: 'A book' });
  const original = await service.create(alice, { title: 'Family exchange', eventDate: '2026-12-25', wishListId: list.id, wishesReviewed: true });
  const id = original.exchangeId;
  const [guest] = await db.insert(schema.members).values({ exchangeId: id, userId: 'bob', name: 'Bob', email: bob.email, status: 'accepted', exchangeRole: 'member' }).returning();
  const [host] = await db.select().from(schema.members).where(and(eq(schema.members.exchangeId, id), eq(schema.members.userId, 'alice')));
  await db.insert(schema.assignments).values({ exchangeId: id, giverMemberId: host.id, receiverMemberId: guest.id });
  await db.insert(schema.exclusions).values({ exchangeId: id, giverMemberId: guest.id, receiverMemberId: host.id });
  await db.update(schema.exchanges).set({ drawnAt: new Date(), joinOpen: true, joinToken: 'old-link', inviteMessage: 'private old invitation' }).where(eq(schema.exchanges.id, id));
  const photo = 'data:image/jpeg;base64,/9j/2Q==';
  await service.tradition(alice, id, { theme: 'Book night', rules: 'Used books welcome', memory: 'The cookbook was a hit', photo, photoApproved: true });
  assert.equal((await service.tradition(bob, id)).tradition.photo, photo);
  await assert.rejects(() => service.tradition(outsider, id), { status: 404 });
  await assert.rejects(() => service.tradition(bob, id, { memory: 'overwrite' }), { status: 404 });
  assert.throws(() => cleanTradition({ photo, photoApproved: false }));
  assert.throws(() => cleanTradition({ photo: 'https://tracker.example/photo.jpg', photoApproved: true }));
  assert.throws(() => cleanTradition({ photo: 'data:image/svg+xml;base64,PHN2Zz4=', photoApproved: true }));
  assert.equal((await service.history(bob)).exchanges.length, 1);
  assert.equal((await service.history(outsider)).exchanges.length, 0);
  await assert.rejects(() => service.create(bob, { title: 'Copy', sourceExchangeId: id }), { status: 404 });
  await assert.rejects(() => service.create(alice, { title: 'Wrong list', wishListId: otherList.id, wishesReviewed: true }), { status: 403 });
  await assert.rejects(() => service.create(alice, { title: 'Stale wishes', wishListId: list.id }), /Review your saved wishes/);
  const next = await service.create(alice, { title: 'Next year', sourceExchangeId: id, wishListId: list.id, wishesReviewed: true, drawnAt: new Date(), joinOpen: true });
  const [nextRow] = await db.select().from(schema.exchanges).where(eq(schema.exchanges.id, next.exchangeId));
  assert.equal(nextRow.drawnAt, null); assert.equal(nextRow.joinOpen, false); assert.equal(nextRow.joinToken, null); assert.equal(nextRow.eventDate, ''); assert.equal(nextRow.inviteMessage, '');
  const nextSeats = await db.select().from(schema.members).where(eq(schema.members.exchangeId, next.exchangeId));
  assert.equal(nextSeats.length, 1); assert.equal(nextSeats[0].userId, 'alice'); assert.equal(nextSeats[0].wishListId, list.id);
  for (const table of [schema.assignments, schema.exclusions, schema.notificationJobs]) assert.equal((await db.select().from(table).where(eq(table.exchangeId, next.exchangeId))).length, 0);
  const memory = (await service.tradition(alice, next.exchangeId)).tradition;
  assert.equal(memory.theme, 'Book night'); assert.equal(memory.rules, 'Used books welcome'); assert.equal(memory.memory, ''); assert.equal(memory.photo, '');
  const startCount = (await db.select().from(schema.exchanges)).length;
  assert.throws(() => nextExchangeValues(alice, { title: 'Invalid date', eventDate: '2027-02-30' }));
  assert.equal((await db.select().from(schema.exchanges)).length, startCount);
  const when = new Date(Date.now() + 86400000).toISOString();
  await assert.rejects(() => service.reminder(bob, id, { runAt: when }), { status: 404 });
  await assert.rejects(() => service.reminder(alice, id, { runAt: '2000-01-01' }), /future/);
  await service.reminder(alice, id, { runAt: when });
  await service.reminder(alice, id, { runAt: when });
  const jobs = await db.select().from(schema.notificationJobs).where(and(eq(schema.notificationJobs.exchangeId, id), eq(schema.notificationJobs.status, 'pending')));
  assert.equal(jobs.length, 1); assert.equal(jobs[0].memberId, host.id); assert.equal(jobs[0].channel, 'email');
  assert.equal((await service.tradition(bob, id)).reminder, null);
  assert.equal(deliveryDecision({ channel: 'email', kind: 'reunion', prefs: { emailReminders: false } }).send, false);
  await service.reminder(alice, id, { cancel: true });
  assert.equal((await service.tradition(alice, id)).reminder, null);
  await service.clearVibe(alice); assert.equal((await service.vibe(alice)).vibe.interests, '');
  await service.tradition(alice, id, {}); assert.equal((await service.tradition(bob, id)).tradition.photo, '');
  console.log('Retention integration passed: all migrations; account isolation; group access; photo permission; fresh exchange privacy; wishlist review/ownership; organizer-only, replaceable reminders; clearing saved data.');
} finally { await engine.close(); }
